/**
 * Subset the Phosphor icon font to the icons the site actually uses.
 *
 * The full @phosphor-icons/web "regular" set ships ~1,500 glyphs (a 144 KB
 * woff2 plus 86 KB of class rules) for about 90 icons. This script:
 *   1. scans the pages and src/ for `ph-<name>` class names (the canvas
 *      kit in visuals/holo reads glyphs by the same class names);
 *   2. writes src/styles/icons.css: the @font-face, the .ph base rule and
 *      only the matching glyph rules, copied from Phosphor's own CSS;
 *   3. subsets Phosphor.ttf to those code points with fontTools
 *      (`pip install fonttools`) into src/assets/fonts/phosphor-subset.woff.
 *
 * Run `npm run icons` after adding an icon anywhere. A class with no glyph
 * fails the run, so a typo cannot ship as a blank square.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const pkg = join(root, "node_modules/@phosphor-icons/web/src/regular");
const OUT_CSS = join(root, "src/styles/icons.css");
const OUT_FONT = join(root, "src/assets/fonts/phosphor-subset.woff");

// Weight and helper classes that are not glyphs.
const NOT_GLYPHS = new Set(["ph-regular", "ph-bold", "ph-light", "ph-thin", "ph-fill", "ph-duotone"]);

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === "dist" || name.startsWith(".")) continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, files);
    else if (/\.(html|js|mjs)$/.test(name)) files.push(path);
  }
  return files;
}

const sources = [
  ...["index.html", "ai-solutions/index.html", "contact/index.html"].map((p) => join(root, p)),
  ...walk(join(root, "src")),
];
const used = new Set();
for (const file of sources) {
  for (const [name] of readFileSync(file, "utf8").matchAll(/\bph-[a-z0-9]+(?:-[a-z0-9]+)*/g)) {
    if (!NOT_GLYPHS.has(name)) used.add(name);
  }
}

const css = readFileSync(join(pkg, "style.css"), "utf8");
const rules = new Map();
for (const [, name, code] of css.matchAll(/\.ph\.(ph-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}/g)) {
  rules.set(name, code);
}

const missing = [...used].filter((name) => !rules.has(name));
if (missing.length) {
  console.error(`No Phosphor glyph for: ${missing.join(", ")}`);
  process.exit(1);
}

const names = [...used].sort();
const codes = [...new Set(names.map((name) => rules.get(name)))];

execFileSync(
  "python",
  [
    "-m",
    "fontTools.subset",
    join(pkg, "Phosphor.ttf"),
    `--unicodes=${codes.map((c) => `U+${c}`).join(",")}`,
    "--flavor=woff",
    "--layout-features=",
    "--no-hinting",
    "--desubroutinize",
    `--output-file=${OUT_FONT}`,
  ],
  { stdio: "inherit" },
);

const glyphRules = names.map((name) => `.ph.${name}:before {\n  content: "\\${rules.get(name)}";\n}`).join("\n");
writeFileSync(
  OUT_CSS,
  `/* Generated by scripts/subset-icons.mjs (npm run icons). Do not edit.
   ${names.length} Phosphor regular icons, subset from @phosphor-icons/web. */

@font-face {
  font-family: "Phosphor";
  src: url("../assets/fonts/phosphor-subset.woff") format("woff");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.ph {
  font-family: "Phosphor" !important;
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  letter-spacing: 0;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${glyphRules}
`,
);

const kb = (statSync(OUT_FONT).size / 1024).toFixed(1);
console.log(`icons: ${names.length} glyphs → ${relative(root, OUT_FONT)} (${kb} KB), ${relative(root, OUT_CSS)}`);
